CREATE TABLE loanops.data_quality_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_run_id BIGINT NOT NULL REFERENCES loanops.source_runs (id),
    raw_snapshot_id BIGINT NOT NULL REFERENCES loanops.raw_snapshots (id),
    record_type VARCHAR(32) NOT NULL,
    record_id BIGINT NOT NULL,
    rule_code VARCHAR(64) NOT NULL,
    field_name VARCHAR(100),
    observed_value VARCHAR(1000),
    message VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT data_quality_issues_record_type_check
        CHECK (record_type IN ('LOAN_PRODUCT', 'PRODUCT_TERM', 'LOAN_RATE_OBSERVATION')),
    CONSTRAINT data_quality_issues_rule_code_check
        CHECK (rule_code IN (
            'REQUIRED_FIELD_MISSING',
            'INVALID_DATE_RANGE',
            'NEGATIVE_RATE',
            'INVALID_RATE_ORDER',
            'NEGATIVE_COUNT'
        )),
    CONSTRAINT data_quality_issues_record_id_check CHECK (record_id > 0),
    CONSTRAINT data_quality_issues_identity_key
        UNIQUE NULLS NOT DISTINCT (
            source_run_id,
            record_type,
            record_id,
            rule_code,
            field_name
        )
);

CREATE TABLE loanops.quarantine_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_run_id BIGINT NOT NULL REFERENCES loanops.source_runs (id),
    raw_snapshot_id BIGINT NOT NULL REFERENCES loanops.raw_snapshots (id),
    record_type VARCHAR(32) NOT NULL,
    record_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT quarantine_records_record_type_check
        CHECK (record_type IN ('LOAN_PRODUCT', 'PRODUCT_TERM', 'LOAN_RATE_OBSERVATION')),
    CONSTRAINT quarantine_records_record_id_check CHECK (record_id > 0),
    CONSTRAINT quarantine_records_identity_key
        UNIQUE (source_run_id, record_type, record_id)
);

CREATE TABLE loanops.publication_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_run_id BIGINT NOT NULL UNIQUE REFERENCES loanops.source_runs (id),
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT publication_runs_status_check
        CHECK (status IN ('PROMOTED', 'REJECTED_QUALITY', 'NO_CHANGE'))
);

CREATE TABLE loanops.serving_loan_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_institution_code VARCHAR(100) NOT NULL,
    source_product_id VARCHAR(200) NOT NULL,
    current_loan_product_id BIGINT NOT NULL UNIQUE REFERENCES loanops.loan_products (id),
    promoted_source_run_id BIGINT NOT NULL REFERENCES loanops.source_runs (id),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT serving_loan_products_identity_key
        UNIQUE (source_institution_code, source_product_id)
);

CREATE TABLE loanops.serving_product_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_institution_code VARCHAR(100) NOT NULL,
    source_product_id VARCHAR(200) NOT NULL,
    mortgage_type_code VARCHAR(20) NOT NULL,
    repayment_type_code VARCHAR(20) NOT NULL,
    lending_rate_type_code VARCHAR(20) NOT NULL,
    current_product_term_id BIGINT NOT NULL UNIQUE REFERENCES loanops.product_terms (id),
    promoted_source_run_id BIGINT NOT NULL REFERENCES loanops.source_runs (id),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT serving_product_terms_identity_key
        UNIQUE (
            source_institution_code,
            source_product_id,
            mortgage_type_code,
            repayment_type_code,
            lending_rate_type_code
        )
);

CREATE TABLE loanops.serving_loan_rate_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_alias_id BIGINT NOT NULL UNIQUE REFERENCES loanops.institution_aliases (id),
    current_loan_rate_observation_id BIGINT NOT NULL UNIQUE REFERENCES loanops.loan_rate_observations (id),
    promoted_source_run_id BIGINT NOT NULL REFERENCES loanops.source_runs (id),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE loanops.data_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publication_run_id BIGINT NOT NULL REFERENCES loanops.publication_runs (id),
    source_run_id BIGINT NOT NULL REFERENCES loanops.source_runs (id),
    record_type VARCHAR(32) NOT NULL,
    stable_record_identity VARCHAR(1000) NOT NULL,
    change_type VARCHAR(16) NOT NULL,
    previous_record_id BIGINT,
    current_record_id BIGINT NOT NULL,
    changed_fields VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT data_changes_record_type_check
        CHECK (record_type IN ('LOAN_PRODUCT', 'PRODUCT_TERM', 'LOAN_RATE_OBSERVATION')),
    CONSTRAINT data_changes_change_type_check
        CHECK (change_type IN ('ADDED', 'UPDATED')),
    CONSTRAINT data_changes_record_ids_check
        CHECK (
            (change_type = 'ADDED' AND previous_record_id IS NULL)
            OR
            (change_type = 'UPDATED' AND previous_record_id IS NOT NULL)
        ),
    CONSTRAINT data_changes_identity_key
        UNIQUE (publication_run_id, record_type, stable_record_identity)
);
