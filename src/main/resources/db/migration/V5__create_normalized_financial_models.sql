CREATE TABLE loanops.financial_institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name VARCHAR(200) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE loanops.institution_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_source_id BIGINT NOT NULL REFERENCES loanops.data_sources (id),
    source_institution_code VARCHAR(100) NOT NULL,
    source_institution_name VARCHAR(200) NOT NULL,
    financial_institution_id BIGINT REFERENCES loanops.financial_institutions (id),
    mapping_status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT institution_aliases_mapping_status_check
        CHECK (mapping_status IN ('MAPPED', 'UNMAPPED')),
    CONSTRAINT institution_aliases_mapping_consistency_check
        CHECK (
            (mapping_status = 'MAPPED' AND financial_institution_id IS NOT NULL)
            OR (mapping_status = 'UNMAPPED' AND financial_institution_id IS NULL)
        ),
    CONSTRAINT institution_aliases_source_identity_key
        UNIQUE (data_source_id, source_institution_code, source_institution_name)
);

CREATE INDEX institution_aliases_financial_institution_id_idx
    ON loanops.institution_aliases (financial_institution_id);

CREATE TABLE loanops.loan_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_alias_id BIGINT NOT NULL REFERENCES loanops.institution_aliases (id),
    financial_institution_id BIGINT NOT NULL REFERENCES loanops.financial_institutions (id),
    raw_snapshot_id BIGINT NOT NULL REFERENCES loanops.raw_snapshots (id),
    source_institution_code VARCHAR(100) NOT NULL,
    source_product_id VARCHAR(200) NOT NULL,
    product_name VARCHAR(300) NOT NULL,
    disclosure_month VARCHAR(6) NOT NULL,
    disclosure_start_date DATE,
    disclosure_end_date DATE,
    source_submitted_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT loan_products_source_identity_key
        UNIQUE (raw_snapshot_id, source_institution_code, source_product_id)
);

CREATE TABLE loanops.product_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_product_id BIGINT NOT NULL REFERENCES loanops.loan_products (id),
    raw_snapshot_id BIGINT NOT NULL REFERENCES loanops.raw_snapshots (id),
    disclosure_month VARCHAR(6) NOT NULL,
    mortgage_type_code VARCHAR(20) NOT NULL,
    mortgage_type_name VARCHAR(100) NOT NULL,
    repayment_type_code VARCHAR(20) NOT NULL,
    repayment_type_name VARCHAR(100) NOT NULL,
    lending_rate_type_code VARCHAR(20) NOT NULL,
    lending_rate_type_name VARCHAR(100) NOT NULL,
    minimum_rate NUMERIC(10, 4) NOT NULL,
    maximum_rate NUMERIC(10, 4) NOT NULL,
    average_rate NUMERIC(10, 4),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT product_terms_source_identity_key
        UNIQUE (
            raw_snapshot_id,
            loan_product_id,
            mortgage_type_code,
            repayment_type_code,
            lending_rate_type_code
        )
);

CREATE TABLE loanops.loan_rate_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_alias_id BIGINT NOT NULL REFERENCES loanops.institution_aliases (id),
    financial_institution_id BIGINT REFERENCES loanops.financial_institutions (id),
    raw_snapshot_id BIGINT NOT NULL REFERENCES loanops.raw_snapshots (id),
    source_institution_code VARCHAR(100) NOT NULL,
    reference_start_date DATE NOT NULL,
    reference_end_date DATE NOT NULL,
    loan_count BIGINT NOT NULL,
    minimum_loan_rate NUMERIC(10, 4) NOT NULL,
    maximum_loan_rate NUMERIC(10, 4) NOT NULL,
    average_loan_rate NUMERIC(10, 4) NOT NULL,
    minimum_loan_ale_rate NUMERIC(10, 4) NOT NULL,
    maximum_loan_ale_rate NUMERIC(10, 4) NOT NULL,
    average_loan_ale_rate NUMERIC(10, 4) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT loan_rate_observations_source_identity_key
        UNIQUE (
            raw_snapshot_id,
            source_institution_code,
            reference_start_date,
            reference_end_date
        )
);

