CREATE TABLE loanops.data_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    response_format VARCHAR(16) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT data_sources_response_format_check
        CHECK (response_format IN ('JSON', 'XML'))
);

CREATE TABLE loanops.source_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_source_id BIGINT NOT NULL REFERENCES loanops.data_sources (id),
    status VARCHAR(16) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 1,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    http_status INTEGER,
    error_type VARCHAR(32),
    error_message VARCHAR(1000),
    retry_of_run_id BIGINT REFERENCES loanops.source_runs (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT source_runs_status_check
        CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
    CONSTRAINT source_runs_attempt_count_check
        CHECK (attempt_count > 0),
    CONSTRAINT source_runs_http_status_check
        CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
    CONSTRAINT source_runs_error_type_check
        CHECK (error_type IS NULL OR error_type IN ('HTTP_ERROR', 'TIMEOUT', 'CONNECTION_ERROR', 'UNKNOWN_ERROR')),
    CONSTRAINT source_runs_state_check
        CHECK (
            (status = 'RUNNING' AND ended_at IS NULL AND error_type IS NULL AND error_message IS NULL)
            OR
            (status = 'SUCCESS' AND ended_at IS NOT NULL AND http_status BETWEEN 200 AND 299
                AND error_type IS NULL AND error_message IS NULL)
            OR
            (status = 'FAILED' AND ended_at IS NOT NULL AND error_type IS NOT NULL AND error_message IS NOT NULL)
        )
);

CREATE INDEX source_runs_data_source_started_at_idx
    ON loanops.source_runs (data_source_id, started_at DESC);

CREATE TABLE loanops.raw_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_run_id BIGINT NOT NULL UNIQUE REFERENCES loanops.source_runs (id),
    data_source_id BIGINT NOT NULL REFERENCES loanops.data_sources (id),
    content_type VARCHAR(200) NOT NULL,
    raw_payload TEXT NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT raw_snapshots_payload_hash_check
        CHECK (payload_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX raw_snapshots_data_source_fetched_at_idx
    ON loanops.raw_snapshots (data_source_id, fetched_at DESC);

